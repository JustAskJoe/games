"""Build Rogue Shooter v2: joins head.html, body.html and src/*.js (in ORDER) into one playable file.

The art in art/sprites/ is embedded as data URIs in a generated src/assets.js, so the build still
runs from file:// with no image requests.
"""
import os, sys, json, base64
HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ['core', 'assets', 'gfx', 'data', 'input', 'state', 'combat', 'ui', 'render', 'farm', 'buildings', 'bmenus', 'main']
OUT = os.path.join(HERE, '..', '..', 'builds', 'rogue-shooter-v2.html')
SPRITES = os.path.join(HERE, '..', '..', 'art', 'sprites')
ASSET_DIRS = ['heroes', 'enemies', 'bosses', 'biomes', 'combat', 'farm', 'ui', 'world']


def write_assets():
    data, manifests = {}, {}
    for d in ASSET_DIRS:
        for name in sorted(os.listdir(os.path.join(SPRITES, d))):
            path, key = os.path.join(SPRITES, d, name), d + '/' + name
            if name.endswith('.png'):
                data[key] = 'data:image/png;base64,' + base64.b64encode(open(path, 'rb').read()).decode()
            elif name.endswith('.json'):
                manifests[key] = json.load(open(path, encoding='utf-8'))
    js = ('// GENERATED by build.py from art/sprites/. Do not edit; rebuild instead.\n'
          'const ASSET_DATA = ' + json.dumps(data) + ';\n'
          'const ASSET_JSON = ' + json.dumps(manifests) + ';\n')
    open(os.path.join(HERE, 'src', 'assets.js'), 'w', encoding='utf-8', newline='\n').write(js)


def build(out=OUT):
    write_assets()
    read = lambda p: open(os.path.join(HERE, p), encoding='utf-8').read()
    js = ''.join(f'// ===== src/{n}.js =====\n' + read(f'src/{n}.js') for n in ORDER)
    html = read('head.html') + read('body.html') + '<script>\n' + js + '</script>\n'
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8', newline='\n').write(html)
    return out


if __name__ == '__main__':
    p = build()
    print('built', os.path.relpath(p, os.getcwd()), f'{os.path.getsize(p) // 1024} KB')
